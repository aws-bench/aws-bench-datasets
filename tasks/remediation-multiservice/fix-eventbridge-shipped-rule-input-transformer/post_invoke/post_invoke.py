LEGACY_INPUT_TEMPLATE = _flat_template(LEGACY_INPUT_PATHS, LEGACY_RULE_NAME)

# EventPattern baselines (all rules share the same source + detailType shape;
# audit rule is source-only).
SHIPPED_EVENT_PATTERN = {"source": [EVENT_SOURCE], "detail-type": ["OrderShipped"]}
AUDIT_EVENT_PATTERN = {"source": [EVENT_SOURCE]}


def _reset_transformer(
    events,
    bus_name: str,
    rule_name: str,
    input_paths: dict[str, str],
    input_template: str,
    label: str,
) -> None:
    """Restore a single rule's target InputTransformer to the CDK baseline.

    Preserves every non-transformer target field verbatim (Id, Arn, RetryPolicy,
    DeadLetterConfig, etc.) so the reset is a targeted transformer rewrite.
    Skips silently if the bus / rule is unset or has no targets.
    """
    if not bus_name or not rule_name:
        return
    try:
        current = events.list_targets_by_rule(
            EventBusName=bus_name, Rule=rule_name
        ).get("Targets", [])
    except ClientError as exc:
        print(
            f"failed to list targets on {rule_name} ({label}): {exc}", file=sys.stderr
        )
        return
    if not current:
        print(f"no targets on {rule_name} ({label}); skipping", file=sys.stderr)
        return

    new_targets: list[dict[str, Any]] = []
    for tgt in current:
        restored = {k: v for k, v in tgt.items() if k not in ("Input", "InputPath")}
        restored["InputTransformer"] = {
            "InputPathsMap": dict(input_paths),
            "InputTemplate": input_template,
        }
        new_targets.append(restored)
    try:
        resp = events.put_targets(
            EventBusName=bus_name, Rule=rule_name, Targets=new_targets
        )
    except ClientError as exc:
        print(f"failed to reset {rule_name} ({label}): {exc}", file=sys.stderr)
        return
    if resp.get("FailedEntryCount", 0):
        print(
            f"put_targets reported failures for {rule_name} ({label}): {resp}",
            file=sys.stderr,
        )
    else:
        print(f"reset {rule_name} ({label}) InputTransformer to CDK baseline")


def _restore_event_pattern(
    events,
    bus_name: str,
    rule_name: str,
    pattern: dict[str, Any],
    enabled: bool,
    description: str,
    label: str,
) -> None:
    """Restore a rule's EventPattern, state and description to baseline.

    ``put_rule`` replaces the whole rule rather than patching it, so every field
    the CDK declares has to be re-supplied: an omitted Description is cleared,
    not preserved. Idempotent and safe to retry; if the rule already matches,
    this still succeeds.
    """
    if not bus_name or not rule_name:
        return
    try:
        events.put_rule(
            Name=rule_name,
            EventBusName=bus_name,
            EventPattern=json.dumps(pattern),
            State="ENABLED" if enabled else "DISABLED",
            Description=description,
        )
        print(f"restored EventPattern / State on {rule_name} ({label})")
    except ClientError as exc:
        print(f"failed to restore rule {rule_name} ({label}): {exc}", file=sys.stderr)


def _reset_audit_rule_target(events) -> None:
    """Restore the audit archive rule target's envelope-only projection.

    The CDK wires the audit rule to a CloudWatch Logs group target whose
    InputTransformer projects only envelope metadata (source, detail-type,
    orderId, ingestion time). Only targets that already have an
    InputTransformer are touched, so no target ARN is fabricated.
    """
    if not PROD_BUS_NAME or not AUDIT_RULE_NAME:
        return
    try:
        current = events.list_targets_by_rule(
            EventBusName=PROD_BUS_NAME, Rule=AUDIT_RULE_NAME
        ).get("Targets", [])
    except ClientError as exc:
        print(
            f"failed to list targets on {AUDIT_RULE_NAME} (audit): {exc}",
            file=sys.stderr,
        )
        return
    if not current:
        print(f"no targets on {AUDIT_RULE_NAME} (audit); skipping", file=sys.stderr)
        return
    new_targets: list[dict[str, Any]] = []
    for tgt in current:
        restored = {k: v for k, v in tgt.items() if k not in ("Input", "InputPath")}
        restored["InputTransformer"] = {
            "InputPathsMap": dict(AUDIT_INPUT_PATHS),
            "InputTemplate": AUDIT_INPUT_TEMPLATE,
        }
        new_targets.append(restored)
    try:
        resp = events.put_targets(
            EventBusName=PROD_BUS_NAME, Rule=AUDIT_RULE_NAME, Targets=new_targets
        )
    except ClientError as exc:
        print(f"failed to reset audit rule targets: {exc}", file=sys.stderr)
        return
    if resp.get("FailedEntryCount", 0):
        print(f"audit rule put_targets reported failures: {resp}", file=sys.stderr)
    else:
        print(f"reset {AUDIT_RULE_NAME} (audit) target to envelope-only projection")


def _remove_extra_prod_rules(events) -> None:
    """Delete any prod-bus rule that is not in the known scenario set."""
    if not PROD_BUS_NAME:
        return
    known = {SHIPPED_RULE_NAME, CANARY_RULE_NAME, AUDIT_RULE_NAME, LEGACY_RULE_NAME}
    # The CDK-shipped placed/returned rules are preserved, not restored.
    placed = os.environ.get("PLACED_RULE_NAME", "fulfillment-order-placed-rule")
    returned = os.environ.get("RETURNED_RULE_NAME", "fulfillment-order-returned-rule")
    known.update({placed, returned})
    kwargs: dict[str, Any] = {"EventBusName": PROD_BUS_NAME}
    while True:
        try:
            resp = events.list_rules(**kwargs)
        except ClientError as exc:
            print(f"list_rules failed: {exc}", file=sys.stderr)
            return
        for rule in resp.get("Rules", []):
            name = rule.get("Name", "")
            if not name or name in known:
                continue
            try:
                targets = events.list_targets_by_rule(
                    EventBusName=PROD_BUS_NAME, Rule=name
                ).get("Targets", [])
                target_ids = [t["Id"] for t in targets if "Id" in t]
                if target_ids:
                    events.remove_targets(
                        EventBusName=PROD_BUS_NAME,
                        Rule=name,
                        Ids=target_ids,
                        Force=True,
                    )
                events.delete_rule(EventBusName=PROD_BUS_NAME, Name=name, Force=True)
                print(f"deleted extra prod-bus rule {name}")
            except ClientError as exc:
                print(f"failed to delete extra rule {name}: {exc}", file=sys.stderr)
        token = resp.get("NextToken")
        if not token:
            return
        kwargs["NextToken"] = token


def _clear_table(
    session: boto3.Session, table_name: str, key_names: tuple[str, ...]
) -> None:
    if not table_name:
        return
    ddb = session.client("dynamodb", region_name=REGION)
    removed = 0
    projection_names = {f"#k{i}": k for i, k in enumerate(key_names)}
    paginator = ddb.get_paginator("scan")
    try:
        for page in paginator.paginate(
            TableName=table_name,
            ProjectionExpression=", ".join(projection_names.keys()),
            ExpressionAttributeNames=projection_names,
        ):
            for item in page.get("Items", []):
                try:
                    ddb.delete_item(
                        TableName=table_name,
                        Key={k: item[k] for k in key_names},
                    )
                    removed += 1
                except ClientError as exc:
                    print(f"delete_item {table_name}: {exc}", file=sys.stderr)
    except ClientError as exc:
        print(f"scan {table_name}: {exc}", file=sys.stderr)
    print(f"cleared {removed} row(s) from {table_name}")


def _purge_dlq(session: boto3.Session) -> None:
    if not TARGET_DLQ_NAME:
        return
    sqs = session.client("sqs", region_name=REGION)
    try:
        queue_url = sqs.get_queue_url(QueueName=TARGET_DLQ_NAME)["QueueUrl"]
    except ClientError as exc:
        print(f"get_queue_url {TARGET_DLQ_NAME}: {exc}", file=sys.stderr)
        return
    try:
        sqs.purge_queue(QueueUrl=queue_url)
        print(f"purged DLQ {TARGET_DLQ_NAME}")
    except ClientError as exc:
        # PurgeQueueInProgress throttles at once per 60s and is not fatal.
        print(f"purge_queue {TARGET_DLQ_NAME} skipped: {exc}", file=sys.stderr)


def main() -> int:
    try:
        session = boto3.Session(region_name=REGION)
        events = session.client("events", region_name=REGION)
        # 1. Production OrderShipped rule: primary reset to broken baseline.
        _reset_transformer(
            events,
            PROD_BUS_NAME,
            SHIPPED_RULE_NAME,
            BROKEN_INPUT_PATHS,
            BROKEN_INPUT_TEMPLATE,
            "prod-shipped",
        )
        _restore_event_pattern(
            events,
            PROD_BUS_NAME,
            SHIPPED_RULE_NAME,
            SHIPPED_EVENT_PATTERN,
            True,
            SHIPPED_RULE_DESCRIPTION,
            "prod-shipped",
        )
        # 2. Staging OrderShipped rule (same name on the staging bus).
        _reset_transformer(
            events,
            STAGING_BUS_NAME,
            SHIPPED_RULE_NAME,
            STAGING_INPUT_PATHS,
            STAGING_INPUT_TEMPLATE,
            "staging-shipped",
        )
        _restore_event_pattern(
            events,
            STAGING_BUS_NAME,
            SHIPPED_RULE_NAME,
            SHIPPED_EVENT_PATTERN,
            True,
            STAGING_RULE_DESCRIPTION,
            "staging-shipped",
        )
        # 3. Log-only canary rule on the prod bus.
        _reset_transformer(
            events,
            PROD_BUS_NAME,
            CANARY_RULE_NAME,
            CANARY_INPUT_PATHS,
            CANARY_INPUT_TEMPLATE,
            "canary",
        )
        _restore_event_pattern(
            events,
            PROD_BUS_NAME,
            CANARY_RULE_NAME,
            SHIPPED_EVENT_PATTERN,
            True,
            CANARY_RULE_DESCRIPTION,
            "canary",
        )
        # 4. Disabled legacy shipped rule on the prod bus.
        _reset_transformer(
            events,
            PROD_BUS_NAME,
            LEGACY_RULE_NAME,
            LEGACY_INPUT_PATHS,
            LEGACY_INPUT_TEMPLATE,
            "legacy",
        )
        _restore_event_pattern(
            events,
            PROD_BUS_NAME,
            LEGACY_RULE_NAME,
            SHIPPED_EVENT_PATTERN,
            False,
            LEGACY_RULE_DESCRIPTION,
            "legacy",
        )
        # 5. Audit archive rule: envelope-only projection.
        _reset_audit_rule_target(events)
        _restore_event_pattern(
            events,
            PROD_BUS_NAME,
            AUDIT_RULE_NAME,
            AUDIT_EVENT_PATTERN,
            True,
            AUDIT_RULE_DESCRIPTION,
            "audit",
        )
        # 6. Delete any ad-hoc rules the agent may have created on the prod bus.
        _remove_extra_prod_rules(events)
        # Clearing here keeps row counts deterministic across trials and drops
        # any AUDIT-PROBE-* rows.
        _clear_table(session, RECORDS_TABLE_NAME, ("orderId", "eventKey"))
        _clear_table(session, SUMMARY_TABLE_NAME, ("tier",))
        _purge_dlq(session)
    except Exception:
        # Never raise: record the traceback and return 0.
        print("post_invoke encountered a non-fatal error:", file=sys.stderr)
        traceback.print_exc(file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
